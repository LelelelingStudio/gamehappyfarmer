/**
 * 根据 id 获取皮肤
 */
function getSkinById(id) {
    return SKINS.find(s => s.id === id) || SKINS[0];
}

/**
 * 获取所有已解锁的皮肤（根据玩家等级）
 * @param {number} level
 * @returns {array}
 */
function getUnlockedSkins(level) {
    return SKINS.filter(s => level >= s.levelRequired);
}

/**
 * 获取下一个即将解锁的皮肤
 * @param {number} level
 * @returns {object|null}
 */
function getNextSkin(level) {
    return SKINS.find(s => level < s.levelRequired) || null;
}